    [Theory]
    [InlineData("valid-still.json", CanonicalStill, StillDigest)]
    [InlineData("valid-clip.json", CanonicalClip, ClipDigest)]
    public void IndependentFixtures_MatchLiteralCanonicalBytesAndDigest(string fixture, string canonical, string digest)
    {
        var result = ArtifactDescriptorContract.Parse(File.ReadAllBytes(FixturePath(fixture)));
        Assert.True(result.Success, result.Error?.ToString());
        Assert.Null(result.Error);
        var descriptor = Assert.IsType<ProvidedArtifactDescriptor>(result.Descriptor);
        Assert.Equal(Encoding.ASCII.GetBytes(canonical), ArtifactDescriptorContract.SerializeCanonical(descriptor));
        Assert.Equal(digest, ArtifactDescriptorContract.ComputeMetadataDigest(descriptor));
        Assert.NotEqual(Convert.ToHexStringLower(SHA256.HashData(Encoding.ASCII.GetBytes(canonical))), digest);
        AssertValid(descriptor);
        // These fixtures contain only independent metadata. Claimed PNGs deliberately do not exist.
        foreach (var file in descriptor.Files)
            Assert.False(File.Exists(Path.Combine(Path.GetDirectoryName(FixturePath(fixture))!, file.Path)));
    }

