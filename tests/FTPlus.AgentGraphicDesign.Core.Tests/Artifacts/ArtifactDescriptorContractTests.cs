    private static ProvidedArtifactDescriptor Inventory(int files, int frames, long width, long height, long byteLength = 1)
    {
        var claims = Enumerable.Range(0, files).Select(i => new ArtifactFileClaim(
            i.ToString("x64", CultureInfo.InvariantCulture), "f" + i.ToString(CultureInfo.InvariantCulture) + ".png", byteLength)).ToImmutableArray();
        return new()
        {
            Schema = "agd.provided-artifact",
            Version = 1,
            Profile = "png8-rgba-srgb-straight-fixed-canvas-v1",
            AssetId = "inventory",
            Canvas = new(width, height, "top-left-pixel-edges-x-right-y-down"),
            CropOrigin = new(0, 0),
            Files = claims,
            Clip = new("clip", "front", "default", 1, "forward-loop", Enumerable.Range(0, frames).Select(i =>
                new ArtifactFrame("f" + i.ToString(CultureInfo.InvariantCulture), claims[i % files].Sha256, 1, new(0, 0))).ToImmutableArray())
        };
    }

    private static ProvidedArtifactDescriptor Still() => Parse(CanonicalStill);
    private static ProvidedArtifactDescriptor Clip() => Parse(CanonicalClip);

    private static ProvidedArtifactDescriptor Parse(string json)
    {
        var result = ArtifactDescriptorContract.Parse(Encoding.UTF8.GetBytes(json));
        Assert.True(result.Success, result.Error?.ToString());
        Assert.Null(result.Error);
        return Assert.IsType<ProvidedArtifactDescriptor>(result.Descriptor);
    }

    private static void AssertValid(ProvidedArtifactDescriptor model)
    {
        Assert.Null(ArtifactDescriptorContract.Validate(model));
        var bytes = ArtifactDescriptorContract.SerializeCanonical(model);
        Assert.InRange(bytes.Length, 1, 1_048_576);
        var result = ArtifactDescriptorContract.Parse(bytes);
        Assert.True(result.Success, result.Error?.ToString());
        Assert.Null(result.Error);
        Assert.Equal(bytes, ArtifactDescriptorContract.SerializeCanonical(result.Descriptor!));
        Assert.Equal(ArtifactDescriptorContract.ComputeMetadataDigest(model), ArtifactDescriptorContract.ComputeMetadataDigest(result.Descriptor!));
    }

    private static ValidationError AssertInvalid(ProvidedArtifactDescriptor model, string code)
    {
        var error = Assert.IsType<ValidationError>(ArtifactDescriptorContract.Validate(model));
        Assert.Equal(code, error.Code);
        Assert.InRange(error.Message.Length, 1, 1024);
        Assert.InRange(error.Path!.Length, 1, 512);
        Assert.Equal(code, Assert.Throws<DocumentEngineException>(() => ArtifactDescriptorContract.SerializeCanonical(model)).Code);
        Assert.Equal(code, Assert.Throws<DocumentEngineException>(() => ArtifactDescriptorContract.ComputeMetadataDigest(model)).Code);
        return error;
    }

    private static void AssertParseError(string json, string code) => AssertFailure(ArtifactDescriptorContract.Parse(Encoding.UTF8.GetBytes(json)), code);

    private static ValidationError AssertFailure(ArtifactDescriptorParseResult result, string code)
    {
        Assert.False(result.Success);
        Assert.Null(result.Descriptor);
        var error = Assert.IsType<ValidationError>(result.Error);
        Assert.Equal(code, error.Code);
        Assert.InRange(error.Message.Length, 1, 1024);
        Assert.InRange(error.Path!.Length, 1, 512);
        return error;
    }

    private static JsonObject ObjectAt(JsonNode root, string path)
    {
        foreach (var segment in path.Split('/', StringSplitOptions.RemoveEmptyEntries))
            root = root is JsonArray array ? array[int.Parse(segment, CultureInfo.InvariantCulture)]! : root[segment]!;
        return root.AsObject();
    }

