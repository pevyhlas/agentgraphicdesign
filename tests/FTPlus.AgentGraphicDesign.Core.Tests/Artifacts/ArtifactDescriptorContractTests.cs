    {
        var model = Inventory(4096, 4096, 1, 1);
        var remaining = 1_048_576 - ArtifactDescriptorContract.SerializeCanonical(model).Length;
        Assert.True(remaining > 0);
        var files = model.Files.ToBuilder();
        for (var i = 0; i < files.Count && remaining > 0; i++)
        {
            var padding = Math.Min(64 - files[i].Path.Length, remaining);
            files[i] = files[i] with { Path = new string('x', padding) + files[i].Path };
            remaining -= padding;
        }
        Assert.Equal(0, remaining);
        model = model with { Files = files.ToImmutable() };
        Assert.Equal(1_048_576, ArtifactDescriptorContract.SerializeCanonical(model).Length);
        AssertValid(model);
        Assert.True(files[^1].Path.Length < 64);
        files[^1] = files[^1] with { Path = "x" + files[^1].Path };
        Assert.Contains("Canonical metadata output", AssertInvalid(model with { Files = files.ToImmutable() }, EngineErrors.ResourceLimit).Message);
    }

