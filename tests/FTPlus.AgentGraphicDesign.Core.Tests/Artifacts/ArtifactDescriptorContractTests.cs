    [InlineData("valid-clip.json", "clip/frames/0")]
    [InlineData("valid-clip.json", "clip/frames/0/pivot")]
    public void EveryObject_IsClosedRejectsNullAndEscapedDuplicatesAndRequiresItsMembers(string fixture, string path)
    {
        var root = JsonNode.Parse(File.ReadAllText(FixturePath(fixture)))!;
        var obj = ObjectAt(root, path);
        obj["unrecognized"] = true;
        AssertParseError(root.ToJsonString(), EngineErrors.ParseError);
        obj.Remove("unrecognized");

        var firstKey = obj.First().Key;
        var spelling = obj.ToJsonString();
        var escapedKey = "\\u" + ((int)firstKey[0]).ToString("x4", CultureInfo.InvariantCulture) + firstKey[1..];
        var duplicate = spelling.Insert(1, "\"" + escapedKey + "\":0,");
        AssertParseError(root.ToJsonString().Replace(spelling, duplicate, StringComparison.Ordinal), EngineErrors.ParseError);

        foreach (var key in obj.Select(property => property.Key).ToArray())
        {
            var saved = obj[key];
            obj[key] = true;
            AssertParseError(root.ToJsonString(), EngineErrors.ParseError);
            obj[key] = null;
            AssertParseError(root.ToJsonString(), EngineErrors.ParseError);
            obj.Remove(key);
            if (path == "provenance" || (path == "" && key == "provenance"))
                Assert.True(ArtifactDescriptorContract.Parse(Encoding.UTF8.GetBytes(root.ToJsonString())).Success);
            else
                AssertParseError(root.ToJsonString(), path == "" && key == "still" ? EngineErrors.InvalidArguments : EngineErrors.ParseError);
            obj[key] = saved;
        }
    }

